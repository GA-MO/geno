import { chmod, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import * as acp from '@agentclientprotocol/sdk';
import { afterEach, describe, expect, it } from 'vitest';
import { GENO_NOTE, WORKSPACE_TRUST_CAPABILITY } from '@g-code/core';
import { gcodeAgent } from '../src/serve.js';
import { call, closeServers, say, scripted } from './conformance/scripted.js';

afterEach(closeServers);

const GENERATED = 'export interface Post {\n  id: string;\n}\n';
const REASON = 'src/payload-types.ts is generated by `payload generate:types`. Change the collection config and run the generator instead.';

// A repository's own guard, as a team commits it for Claude Code: it refuses edits to the generated types file.
const GUARD = [
  '#!/bin/sh',
  'in=$(cat)',
  'case "$in" in',
  `  *'"file_path":"'*payload-types.ts'"'*) printf '%s\\n' '${JSON.stringify({ hookSpecificOutput: { hookEventName: 'PreToolUse', permissionDecision: 'deny', permissionDecisionReason: REASON } })}' ;;`,
  'esac',
  'exit 0',
  '',
].join('\n');

describe('a PreToolUse hook in the workspace, over ACP', () => {
  it('blocks an edit of a generated file, and the model reads why, while other edits go through', async () => {
    const blocked = { id: 'tu_generated', name: 'edit', input: { path: 'src/payload-types.ts', old_str: 'id: string;', new_str: 'id: number;' } };
    const allowed = { id: 'tu_config', name: 'edit', input: { path: 'src/collections.ts', new_str: 'export const posts = { slug: "posts" };\n', create: true } };
    const run = await scripted('anthropic', [call('', [blocked]), call('', [allowed]), say('I changed the collection config instead.')], { 'src/payload-types.ts': GENERATED });
    const hooks = path.join(run.workspace, '.claude', 'hooks');
    await mkdir(hooks, { recursive: true });
    await writeFile(path.join(hooks, 'protect-generated.sh'), GUARD);
    await chmod(path.join(hooks, 'protect-generated.sh'), 0o755);
    const command = '"$CLAUDE_PROJECT_DIR"/.claude/hooks/protect-generated.sh';
    await writeFile(path.join(run.workspace, '.claude', 'settings.json'), JSON.stringify({ hooks: { PreToolUse: [{ matcher: 'Edit|Write', hooks: [{ type: 'command', command }] }] } }));

    const updates: acp.SessionNotification[] = [];
    const editor = acp.client({ name: 'e2e' }).onNotification(acp.methods.client.session.update, ({ params }) => void updates.push(params));
    await editor.connectWith(gcodeAgent(run.io, run.store, { maxTurns: 10, maxCostUsd: 1 }), async (ctx) => {
      await ctx.request(acp.methods.agent.initialize, { protocolVersion: acp.PROTOCOL_VERSION, clientCapabilities: { _meta: { [WORKSPACE_TRUST_CAPABILITY]: true } } });
      const { sessionId } = await ctx.request(acp.methods.agent.session.new, { cwd: run.workspace, mcpServers: [] });
      await ctx.request(acp.methods.agent.session.prompt, { sessionId, prompt: [{ type: 'text', text: 'Make Post ids numbers.' }] });
    });

    const [first, second] = run.seen().slice(1);
    expect(first!.results).toEqual([{ id: 'tu_generated', error: true, text: `${GENO_NOTE} PreToolUse:Edit hook error: ${REASON}` }]);
    expect(second!.results[0]).toMatchObject({ id: 'tu_config', error: false });
    expect(await readFile(path.join(run.workspace, 'src', 'payload-types.ts'), 'utf8')).toBe(GENERATED);
    expect(await readFile(path.join(run.workspace, 'src', 'collections.ts'), 'utf8')).toContain('slug: "posts"');
    const failed = updates.flatMap(({ update }) => (update.sessionUpdate === 'tool_call_update' && update.toolCallId === 'tu_generated' ? [update.status] : []));
    expect(failed, 'the editor shows the blocked edit as failed').toContain('failed');
  });
});
