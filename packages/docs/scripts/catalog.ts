import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { stringify } from 'yaml';
import type { CatalogIn } from '../src/scenario/schema.js';

const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/data/catalog.yaml');

const CHAPTER = /^## (\d+)\. (.+): \d+$/;
const NAMED = /^(.+?) \((.+)\)$/;

const cellsOf = (line: string): string[] => line.slice(1, -1).split('|').map((cell) => cell.trim());
const unticked = (cell: string): string => cell.replace(/^`|`$/g, '');
const cellPerId = (cell: string, count: number): string[] => {
  const parts = cell.split(' / ');
  return parts.length === count ? parts : Array.from({ length: count }, () => cell);
};

function parseCatalog(markdown: string): CatalogIn {
  const catalog: CatalogIn = { chapters: [], scenarios: [] };
  for (const line of markdown.split('\n')) {
    const heading = CHAPTER.exec(line);
    if (line.startsWith('## ') && heading === null && catalog.chapters.length > 0) break;
    if (heading !== null) {
      const number = heading[1]!;
      const title = heading[2]!;
      const named = NAMED.exec(title);
      catalog.chapters.push({ number: Number(number), prefix: '', thai: named?.[1] ?? title, english: named?.[2] ?? title });
      continue;
    }
    if (!line.startsWith('| `')) continue;
    const chapter = catalog.chapters.at(-1);
    const cells = cellsOf(line);
    if (chapter === undefined || cells.length !== 8) throw new Error(`catalog row outside a chapter or not 8 cells: ${line}`);
    const [ids, thai, english, , , lanes, terminal, priority] = cells as [string, string, string, string, string, string, string, string];
    const each = ids.split(' / ').map(unticked);
    const thais = cellPerId(thai, each.length);
    const englishes = cellPerId(english, each.length);
    each.forEach((id, i) => {
      chapter.prefix = id.split('.')[0] ?? '';
      catalog.scenarios.push({
        id,
        thai: thais[i] ?? thai,
        english: englishes[i] ?? english,
        chapter: chapter.number,
        priority: priority as 'P1' | 'P2' | 'P3',
        lanes: lanes.split(',').map((lane) => lane.trim()),
        terminal,
      });
    });
  }
  return catalog;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const source = process.argv[2];
  if (source === undefined) throw new Error('usage: catalog <catalog.md>');
  const catalog = parseCatalog(readFileSync(source, 'utf8'));
  writeFileSync(OUT, `# Generated by scripts/catalog.ts from the explorers' catalog.md. Do not edit by hand.\n${stringify(catalog, { lineWidth: 0 })}`);
  console.log(`catalog: ${catalog.chapters.length} chapters, ${catalog.scenarios.length} scenarios -> ${path.relative(process.cwd(), OUT)}`);
}
